"""Hermes frontend map validity: the machine-readable source comparison
stays complete and honest.

`docs/archive/2026-09-21/HERMES_FRONTEND_MAP.json` (generated by
`scripts/hermes_frontend_map.py` against the pinned oracle) must cover
every Hermes web/src file, every built-in route, and every inventoried
endpoint with an explicit disposition — no silent omission. Regeneration
asserts the oracle pin itself.
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
MAP = REPO_ROOT / "docs/archive/2026-09-21" / "HERMES_FRONTEND_MAP.json"
GEN = REPO_ROOT / "scripts" / "hermes_frontend_map.py"

EXPECTED_ROUTES = {"/chat", "/sessions", "/files", "/analytics", "/models",
                   "/logs", "/cron", "/skills", "/plugins", "/mcp",
                   "/channels", "/webhooks", "/pairing", "/profiles",
                   "/profiles/new", "/config", "/env", "/system", "/docs"}


def _load():
    return json.loads(MAP.read_text())


def test_map_exists_and_pins_match_provenance():
    doc = _load()
    assert doc["source"]["revision"] == \
        "2237be355906fbe6065ce1815711eee52b2d646e"
    assert doc["source"]["license"].startswith("MIT")
    inv = json.loads((REPO_ROOT / "docs/archive/2026-09-21" / "INVENTORY_HERMES.json").read_text())
    assert inv["commit"] == doc["source"]["revision"]


def test_map_covers_every_route():
    doc = _load()
    assert set(doc["routes"]) == EXPECTED_ROUTES
    for route, row in doc["routes"].items():
        assert row["qubit"] and row["disposition"] and row["note"], route
        assert row["disposition"] in ("adapted", "partial"), route


def test_map_covers_every_endpoint_prefix():
    doc = _load()
    assert len(doc["endpoints"]) >= 70, len(doc["endpoints"])
    for prefix, row in doc["endpoints"].items():
        assert row["qubit"] and row["disposition"], prefix
        disp = row["disposition"].split(":")[0]
        assert disp in ("adapted", "partial", "REFUSED", "OMITTED"), prefix
        if disp in ("REFUSED", "OMITTED"):
            assert len(row["disposition"]) > len(disp) + 1, prefix


def test_map_covers_every_frontend_file():
    doc = _load()
    files = doc["files"]
    assert len(files) == 170, len(files)
    kinds = {f["kind"] for f in files}
    assert {"page", "component", "lib", "i18n", "test", "shell",
            "context"} <= kinds
    for f in files:
        assert len(f["sha256"]) == 64, f["path"]
        assert f["disposition"], f["path"]
    pages = sorted(f["path"] for f in files if f["kind"] == "page")
    assert len(pages) == 19, pages


def test_generator_reproduces_map_and_asserts_pin(tmp_path):
    oracle = Path("/tmp/pinned-upstream/hermes-agent/web/src")
    if not oracle.is_dir():
        pytest.skip("pinned oracle absent")
    r = subprocess.run(["git", "-C", "/tmp/pinned-upstream/hermes-agent",
                        "rev-parse", "HEAD"], capture_output=True, text=True,
                       timeout=60)
    assert r.stdout.strip() == \
        "2237be355906fbe6065ce1815711eee52b2d646e"
    before = MAP.read_text()
    r = subprocess.run([".venv/bin/python",
                        "scripts/hermes_frontend_map.py"],
                       capture_output=True, text=True, cwd=str(REPO_ROOT),
                       timeout=120)
    assert r.returncode == 0, r.stderr[-1000:]
    assert MAP.read_text() == before, "map not reproducible — commit the regen"
