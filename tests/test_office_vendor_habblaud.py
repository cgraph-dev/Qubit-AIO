"""Drift detection for the vendored Habblaud client in the Qubit Office plugin.

``frontend/qubit-app/plugins/qubit-office/habblaud/`` is a BUILD ARTIFACT: 77
hash-named files regenerated by ``scripts/vendor_habblaud.py`` from a checkout
passed via ``--src``. That checkout does not exist on a fresh clone or in CI, so
nothing here rebuilds. What this module guarantees instead is that the vendored
tree never SILENTLY drifts from the record the script wrote next to it:

* every file in ``PROVENANCE.json`` is present with the recorded sha256;
* no file is present that the record does not name (an undeclared file is how a
  stray artifact — or a hand-edit — ships unnoticed);
* the MIT licence travelled with the copies, as the script's docstring promises;
* the record names the upstream repo, commit and licence, so reproduction points
  at an actual revision rather than "some build we did once";
* no absolute build-time path leaked into the served bytes;
* the absolute-path remap the script exists to perform actually happened — both
  the ``index.html`` href/src rewrite AND the separate CSS webfont rewrite.

Why (f) and (g) are separate invariants
---------------------------------------
``index.html`` carries absolute ``href``/``src`` references (``/bundle/main-<hash>.js``,
``/assets/brand/favicon-32.png``) and ``rewrite_index`` maps them onto the
plugin prefix. The stylesheets carry a DIFFERENT absolute form — ``url(/bundle/pixelify-sans-….woff2)``
inside the CSS ``@font-face`` rules — which lives in ``.css`` files that
``rewrite_index`` never opens; ``rewrite_css`` handles those. Miss the former and
every script/icon 404s (the page fails loudly); miss the latter and the page
loads and renders but silently falls back to a system font (the bug the script's
own docstring records as "the pixel font didn't build"). A single regex over
whatever "contains a path" would not distinguish the two surfaces, so a
regression in one would mask a pass in the other — hence two assertions.

Hermetic: pure filesystem reads of the checked-in tree. No network, no
``/tmp/habblaud-full``, no subprocess.
"""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
VENDOR = (
    REPO / "frontend" / "qubit-app" / "plugins" / "qubit-office" / "habblaud"
)
PROVENANCE = VENDOR / "PROVENANCE.json"

#: The plugin's own served prefix — mirrored from scripts/vendor_habblaud.py.
ASSET_PREFIX = "/plugin-apps/qubit-office/habblaud"

pytestmark = pytest.mark.unit


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _load_provenance() -> dict:
    if not PROVENANCE.is_file():
        pytest.fail(f"PROVENANCE.json is missing from the vendored tree at {PROVENANCE}")
    return json.loads(PROVENANCE.read_text(encoding="utf-8"))


def _list_record(record: dict) -> dict[str, dict]:
    return {f["path"]: f for f in record["files"]}


def _all_vendored_files() -> list[str]:
    """Every file under the vendored tree, relative to its root."""
    return sorted(
        str(p.relative_to(VENDOR)) for p in VENDOR.rglob("*") if p.is_file()
    )


# --- (a) every recorded file exists and hashes to its recorded value --------


def test_recorded_files_exist_and_match_hashes() -> None:
    record = _load_provenance()
    listed = _list_record(record)
    assert listed, "PROVENANCE.json lists no files"

    missing: list[str] = []
    mismatched: list[tuple[str, str, str]] = []
    for rel, entry in sorted(listed.items()):
        target = VENDOR / rel
        if not target.is_file():
            missing.append(rel)
            continue
        actual = _sha256(target)
        if actual != entry["sha256"]:
            mismatched.append((rel, entry["sha256"], actual))

    assert not missing, f"recorded vendored files missing from disk: {missing}"
    assert not mismatched, (
        "vendored files whose sha256 no longer matches PROVENANCE.json "
        f"(path, recorded, actual): {mismatched}"
    )


def test_recorded_byte_sizes_agree_with_disk() -> None:
    """``bytes`` is part of the record; an out-of-band edit changes it too."""
    record = _load_provenance()
    bad = [
        (rel, entry["bytes"], (VENDOR / rel).stat().st_size)
        for rel, entry in _list_record(record).items()
        if (VENDOR / rel).is_file()
        and (VENDOR / rel).stat().st_size != entry["bytes"]
    ]
    assert not bad, f"recorded byte sizes disagree with disk: {bad}"


def test_total_bytes_matches_sum_of_recorded_files() -> None:
    record = _load_provenance()
    summed = sum(f["bytes"] for f in record["files"])
    assert record["total_bytes"] == summed, (
        f"total_bytes={record['total_bytes']} but the listed files sum to {summed}"
    )


# --- (b) no undeclared file ships -------------------------------------------


def test_no_vendored_file_is_undeclared() -> None:
    record = _load_provenance()
    declared = set(_list_record(record)) | {"PROVENANCE.json"}
    on_disk = set(_all_vendored_files())
    undeclared = sorted(on_disk - declared)
    assert not undeclared, (
        "vendored files present on disk but absent from PROVENANCE.json "
        f"(an undeclared artifact would ship unrecorded): {undeclared}"
    )


def test_record_and_disk_agree_on_file_count() -> None:
    record = _load_provenance()
    # disk includes PROVENANCE.json, which the record deliberately excludes.
    assert len(_all_vendored_files()) == len(record["files"]) + 1, (
        "PROVENANCE.json file count does not cover the vendored tree: "
        f"{len(record['files'])} recorded vs "
        f"{len(_all_vendored_files()) - 1} on disk (minus PROVENANCE.json)"
    )


# --- (c) the licence travels and is MIT -------------------------------------


def test_upstream_license_ships_and_is_mit() -> None:
    license_file = VENDOR / "LICENSE"
    assert license_file.is_file(), (
        "the vendored tree carries no LICENSE — Habblaud is MIT and its NOTICE "
        "must travel with the copies (scripts/vendor_habblaud.py docstring)"
    )
    text = license_file.read_text(encoding="utf-8")
    assert "MIT License" in text, "vendored LICENSE is not the MIT licence text"
    assert "Permission is hereby granted, free of charge" in text, (
        "vendored LICENSE lacks the MIT grant clause"
    )


def test_license_is_declared_in_the_record_too() -> None:
    license_file = VENDOR / "LICENSE"
    if not license_file.is_file():
        pytest.fail("no LICENSE to cross-check against the record")
    record = _load_provenance()
    entry = _list_record(record).get("LICENSE")
    assert entry is not None, "PROVENANCE.json does not record the bundled LICENSE"
    assert entry["sha256"] == _sha256(license_file), (
        "the bundled LICENSE differs from the hash recorded in PROVENANCE.json"
    )


# --- (d) the record names repo, commit and licence --------------------------


def test_provenance_names_repo_commit_and_licence() -> None:
    record = _load_provenance()

    assert record.get("source", "").startswith("https://github.com/"), (
        f"provenance does not name an upstream repo URL: {record.get('source')!r}"
    )
    assert "habblaud" in record["source"].lower()

    commit = record.get("commit", "")
    assert re.fullmatch(r"[0-9a-f]{40}", commit), (
        f"provenance commit is not a full 40-hex git sha: {commit!r} "
        "(reproduction must point at an exact revision, not 'unknown')"
    )
    assert commit != "unknown"

    assert record.get("licence") == "MIT", (
        f"provenance does not record the MIT licence: {record.get('licence')!r}"
    )


# --- (e) no absolute build path leaked into the served output ---------------


def test_no_absolute_source_path_leaks_into_vendored_files() -> None:
    """No vendored file may embed the build-host checkout path.

    The invariant is narrower than "contains something that looks like a path".
    Upstream ships a demo/simulator constant — ``shared/demo/simulator.ts``:
    ``const ROOT = '/Users/dev/projetos'`` — which is intentional fixture data,
    byte-identical in every clone of the pinned commit, and NOT a leak from this
    machine's build. What must never appear is the ``--src`` checkout path the
    build actually ran from, or any absolute path to a builder's home that
    upstream does not itself ship.
    """
    build_src_marker = b"/tmp/habblaud-full"
    leaks: list[tuple[str, str]] = []
    for rel in _all_vendored_files():
        if rel == "PROVENANCE.json":
            # The record legitimately describes where it came from; only the
            # served bytes must be free of build-time paths.
            continue
        blob = (VENDOR / rel).read_bytes()
        if build_src_marker in blob:
            leaks.append((rel, build_src_marker.decode()))
    assert not leaks, (
        "the build-host checkout path leaked into served vendored files "
        f"(file, needle): {leaks}"
    )


def test_upstream_demo_path_is_the_only_users_reference() -> None:
    """Every ``/Users/`` string must be upstream's own demo/i18n placeholder set.

    ``/Users/dev/projetos`` (demo simulator) and the localized example paths
    ``/Users/voce/projeto`` (pt), ``/Users/you`` (en), ``/Users/tu`` (es),
    ``/Users/vous`` (fr) all come from the pinned upstream source. If the
    vendored output ever contains a ``/Users/`` path that is NOT one of these
    upstream-owned constants, it did not come from that commit and is a leak.
    """
    allowed_prefixes = (
        "/Users/dev/projetos",
        "/Users/voce",
        "/Users/you",
        "/Users/tu",
        "/Users/vous",
    )
    unexpected: list[tuple[str, str]] = []
    for rel in _all_vendored_files():
        if rel == "PROVENANCE.json":
            continue
        text = (VENDOR / rel).read_text(encoding="utf-8", errors="replace")
        # Match a full path segment run so the comparison sees the whole token,
        # not a truncated one (``/Users/dev`` vs ``/Users/dev/projetos``).
        for match in re.finditer(r"/Users/[A-Za-z0-9._/-]*", text):
            if not match.group(0).startswith(allowed_prefixes):
                unexpected.append((rel, match.group(0)))
    assert not unexpected, (
        "vendored files contain a home-directory path that is not one of "
        f"upstream's own demo/i18n constants: {unexpected}"
    )


def test_provenance_does_not_point_at_a_machine_local_checkout() -> None:
    raw = PROVENANCE.read_text(encoding="utf-8")
    # The record must be portable across machines: it names the upstream repo and
    # commit, never the absolute --src path the build happened to run from.
    for needle in ("/tmp/habblaud-full",):
        assert needle not in raw, (
            f"PROVENANCE.json embeds the local build path {needle!r}; "
            "the record must be portable across machines"
        )


# --- (f) index.html absolute /bundle and /assets refs were remapped ---------


def test_index_html_has_no_absolute_bundle_or_assets_refs() -> None:
    index = VENDOR / "index.html"
    assert index.is_file(), "vendored index.html is missing"
    html = index.read_text(encoding="utf-8")

    # A rooted reference that is NOT already the plugin prefix is exactly the
    # un-remapped form that 404s against the host. Match a leading-slash ref
    # that is not preceded by the prefix, across the attributes that carry a
    # fetched URL: href, src, and the meta-image `content`.
    offenders: list[str] = []
    for attr, url in re.findall(r'\b(href|src|content)="(/[^"]*)"', html):
        if url.startswith(ASSET_PREFIX):
            continue
        if "/bundle/" in url or url.startswith("/assets/"):
            offenders.append(f"{attr}={url}")
    assert not offenders, (
        "index.html still carries absolute asset references that would 404 "
        f"against the Qubit dashboard: {offenders}"
    )


def test_index_html_meta_image_refs_use_the_plugin_prefix() -> None:
    """og:image / twitter:image carry fetched URLs in `content=`, not href/src.

    They 404 exactly like an un-remapped src if the rewriter only knows
    href/src — the bug this test pins.
    """
    html = (VENDOR / "index.html").read_text(encoding="utf-8")
    meta_images = re.findall(
        r'<meta\s+[^>]*content="([^"]+)"[^>]*>', html
    )
    asset_meta = [m for m in meta_images if "/assets/" in m or "/bundle/" in m]
    assert asset_meta, (
        "index.html declares no meta image content= refs — the og:image/"
        "twitter:image path-rewrite surface is no longer exercised"
    )
    for ref in asset_meta:
        assert ref.startswith(ASSET_PREFIX + "/"), (
            f"meta content= reference is not plugin-relative: {ref!r}"
        )


def test_index_html_asset_refs_use_the_plugin_prefix() -> None:
    html = (VENDOR / "index.html").read_text(encoding="utf-8")
    # The build emits hash-named chunks under /bundle and fixed assets under
    # /assets; after remap every such reference must carry the prefix.
    srcs = re.findall(r'src="([^"]+)"', html) + re.findall(r'href="([^"]+)"', html)
    plugin_refs = [s for s in srcs if "/bundle/" in s or "/assets/" in s]
    assert plugin_refs, "index.html references no bundle/assets files at all"
    for ref in plugin_refs:
        assert ref.startswith(ASSET_PREFIX + "/"), (
            f"index.html asset reference is not plugin-relative: {ref!r}"
        )


def test_index_html_references_resolve_within_the_vendored_tree() -> None:
    """Every /bundle/... and /assets/... ref maps to a file that actually ships."""
    html = (VENDOR / "index.html").read_text(encoding="utf-8")
    refs = re.findall(r'(?:src|href)="([^"]+)"', html)
    checked = 0
    for ref in refs:
        if not ref.startswith(ASSET_PREFIX + "/"):
            continue
        rel = ref[len(ASSET_PREFIX) + 1:]
        assert (VENDOR / rel).is_file(), (
            f"index.html points at {ref} but {rel} is not in the vendored tree"
        )
        checked += 1
    assert checked, "no plugin-prefixed references found to verify"


# --- (g) the CSS webfont rewrite happened -----------------------------------


def test_css_has_no_absolute_bundle_url() -> None:
    css_files = list(VENDOR.rglob("*.css"))
    assert css_files, "the vendored tree ships no stylesheet"
    offenders: list[tuple[str, str]] = []
    for css in css_files:
        text = css.read_text(encoding="utf-8")
        for match in re.finditer(r"url\((/[^)]*)\)", text):
            url = match.group(1)
            if not url.startswith(ASSET_PREFIX):
                offenders.append((str(css.relative_to(VENDOR)), url))
    assert not offenders, (
        "stylesheets still carry absolute url() references — the webfont "
        f"rewrite is missing and fonts would 404: {offenders}"
    )


def test_index_rewrite_and_css_rewrite_are_distinct_surfaces() -> None:
    """Guard against collapsing (f) and (g) into one misleading check.

    index.html contains no ``url(...)`` and the CSS contains no ``href``/``src``;
    if either invariant is dropped because "the other one covers it", the real
    difference between the two remaps is lost. This test asserts that the two
    surfaces genuinely differ, so neither assertion is redundant.
    """
    html = (VENDOR / "index.html").read_text(encoding="utf-8")
    css_files = list(VENDOR.rglob("*.css"))
    assert re.search(r"url\(", html) is None, (
        "index.html unexpectedly contains url() — the (f)/(g) split assumption "
        "no longer holds; reconsider the remap surfaces"
    )
    assert not any(
        re.search(r'\b(?:href|src)="', c.read_text(encoding="utf-8"))
        for c in css_files
    ), (
        "a stylesheet unexpectedly contains href/src — the (f)/(g) split "
        "assumption no longer holds"
    )
