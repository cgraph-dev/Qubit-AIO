# ships its own test suite, so an upstream ``*.test.*`` file is never required
# to be vendored into the product.
_REFERENCE_ONLY_SUFFIXES = (".test.ts", ".test.tsx", ".test.js", ".test.jsx")


def _reference_only(rel: str) -> bool:
    return ("/__tests__/" in rel or rel.endswith(_REFERENCE_ONLY_SUFFIXES))


def _unaccounted_product_missing(upstream_files, local_by_upstream, prefix,
                                 recorded_remainder):
    """Product (non-reference-only) upstream files with no local counterpart.

    A file is accounted for when it is vendored locally (present in
    ``local_by_upstream``) or explicitly recorded in the canonical frontend
    comparison ledger as a tracked not-yet-vendored remainder. Reference-only
    upstream unit tests are omitted by policy and never required.
    """
    unaccounted = []
    for rel in sorted(set(upstream_files) - set(local_by_upstream)):
        if _reference_only(rel):
            continue
        if f"{prefix}/{rel}" in recorded_remainder:
            continue
        unaccounted.append(rel)
    return unaccounted

