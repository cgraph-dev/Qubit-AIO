_DEFAULT_BUDGET = {
    "monthly_minor": 25_000,
    "per_action_minor": 2_500,
    "rate_limit_per_hour": 120,
    "currency": DEFAULT_CURRENCY,
}


def _uniq(items: Iterable[str]) -> tuple[str, ...]:
    return tuple(dict.fromkeys(items))


def _r(
    role_id: str,
    department: str,
    title: str,
    mission: str,
    responsibilities: Sequence[str],
    *,
    permissions: Sequence[str],
    extra_skills: Sequence[str] = (),
    extra_toolsets: Sequence[str] = (),
    data_scopes: Sequence[str] | None = None,
    approvals: Sequence[str] = (),
    autonomy: str = "L2",
    service_lines: Sequence[str] = (),
    budget: dict[str, Any] | None = None,
    schedule: str = "business_hours",
    kpis: Sequence[str] | None = None,
    escalation: str | None = None,
    provider_hint: str = "opencode-go",
    model_hint: str = "deepseek-v4.1-flash",
    human_owner: str | None = None,
    sop_refs: Sequence[str] | None = None,
    memory_refs: Sequence[str] | None = None,
    active_by_default: bool = True,
) -> RoleTemplate:
    owner = human_owner or _OWNER_BY_DEPT[department]
    perms = _uniq(permissions)
    toolsets = _uniq((*_DEPT_TOOLSETS[department], *extra_toolsets))
    gates = tuple(
        sorted(set(approvals) | set(required_approvals(perms, toolsets)))
    )
    payload = dict(_DEFAULT_BUDGET if budget is None else budget)
    payload.setdefault("currency", DEFAULT_CURRENCY)
    return RoleTemplate(
        id=role_id,
        department=department,
        title=title,
        mission=mission,
        responsibilities=tuple(responsibilities),
        skills=_uniq((*_DEPT_SKILLS[department], *extra_skills)),
        toolsets=toolsets,
        data_scopes=tuple(
            data_scopes or (f"business.{department}",)
        ),
        permissions=perms,
        budget=payload,
        autonomy=autonomy,
        approvals=gates,
        schedule=schedule,
        kpis=tuple(kpis or _DEPT_KPIS[department]),
        escalation=escalation
        or f"escalate to {owner} with task id, evidence and last action",
        model={"provider_hint": provider_hint, "model_hint": model_hint},
        sop_refs=tuple(
            sop_refs or (f"sop:{department}/{role_id}",)
        ),
        memory_refs=tuple(memory_refs or (f"memory:{department}",)),
        human_owner=owner,
        service_lines=tuple(service_lines),
        active_by_default=active_by_default,
    )


