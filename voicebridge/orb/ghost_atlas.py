"""The ghost sprite atlas — frames exported from the real pixelfx effect.

The ghost is NOT redrawn here. ``qubit_runtime/vendor/pixelfx/export_ghost.mjs``
runs the upstream effect (``src/fx/critters/ghost.js``, MIT, Copyright (c) 2026
Patch) through its own Painter and writes every frame of the loop as RGBA. This
module loads that atlas and hands the Qt painter a QImage for the frame the orb
clock is on, so the orb shows the original artwork pixel-for-pixel.

Why a sprite instead of a field: the orb's other marks are vector constructions
(rings, particles, nucleus) described analytically. The ghost is hand-authored
pixel art with a skeleton and a grid-shaded sheet; approximating it with vector
primitives would lose exactly what makes it read as a ghost. Blitting the real
frames is both faithful and cheaper than re-deriving the silhouette per frame.

Missing atlas is not an error: :func:`frame_at` returns ``None`` and the painter
falls back to the vector mark, so an orb built from a source checkout without the
generated atlas still paints.
"""
from __future__ import annotations

import json
import math
import struct
from pathlib import Path
from typing import Any, Dict, Optional, Tuple

#: Serialised frame atlas (header JSON, NUL, then RGBA frames). Generated by
#: ``qubit_runtime/vendor/pixelfx/export_ghost.mjs``; see that script for the
#: exact upstream pin and the licence line.
ATLAS_FILENAME = "ghost_atlas.bin"

#: Art span the ghost BODY is scaled by, not the padded canvas.
#:
#: The exporter pads the frame with `margin` 60 so the outer glow fits: the atlas
#: is 216x220 while the ghost itself occupies only ~32x45 of that (measured on
#: frame 18: body bbox x 94..126, y 107..152). Scaling the PADDED canvas to the
#: orb diameter therefore sized the halo to the orb and left the ghost at ~22% of
#: it — the "too small" defect.
#:
#: 85 is measured, not guessed. On a 336px canvas with the orb at R=120:
#:   ART_SPAN=70  body 112x156  halo 314x287  CLIPPED at the widget edge
#:   ART_SPAN=85  body  93x128  halo 264x262  fits
#:   ART_SPAN=100 body  79x109  halo 224x222  fits, ghost visibly small
#: 85 is the largest value where the halo still falls off to nothing inside the
#: widget, so the glow reads as a circle instead of a cut square.
ART_SPAN = 85.0

_MAGIC = b""


def atlas_path() -> Optional[Path]:
    """Locate the atlas in a source checkout OR an installed package.

    Two layouts exist and both must work:
      source    <repo>/voicebridge/orb/  + <repo>/qubit_runtime/vendor/pixelfx/
      installed <site-packages>/voicebridge/orb/ + <pkg>/_data/qubit_runtime/vendor/pixelfx/

    The installed package keeps bulk assets under ``_data``, so a single
    ``../..`` hop is wrong there — that lands on ``site-packages``. Enumerate the
    real candidates instead of assuming one depth.
    """
    here = Path(__file__).resolve().parent          # .../voicebridge/orb
    pkg = here.parent                               # .../voicebridge
    candidates = [
        here / ATLAS_FILENAME,                      # beside this module
        pkg / ATLAS_FILENAME,
        pkg / "_data" / "qubit_runtime" / "vendor" / "pixelfx" / ATLAS_FILENAME,
        pkg.parent / "qubit_runtime" / "vendor" / "pixelfx" / ATLAS_FILENAME,
    ]
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    return None


class _Atlas:
    """Parsed atlas: header plus the raw RGBA body."""

    __slots__ = ("header", "body", "w", "h", "frames", "fps", "duration")

    def __init__(self, raw: bytes) -> None:
        header_raw, _, body = raw.partition(b"\x00")
        header = json.loads(header_raw)
        self.header: Dict[str, Any] = header
        self.body = body
        self.w = int(header["w"])
        self.h = int(header["h"])
        self.frames = int(header["frames"])
        self.fps = float(header["fps"])
        self.duration = float(header["duration"])

    def rgba(self, index: int) -> bytes:
        size = self.w * self.h * 4
        offset = (index % self.frames) * size
        return self.body[offset:offset + size]


_CACHE: Dict[str, Any] = {"atlas": None, "mtime": None, "loaded": False}
_IMAGE_CACHE: Dict[int, Any] = {}


def _atlas() -> Optional[_Atlas]:
    """Load (and cache) the atlas, reloading when the file changes."""
    path = atlas_path()
    if path is None:
        return None
    try:
        mtime = path.stat().st_mtime
    except OSError:
        return None
    if _CACHE["loaded"] and _CACHE["mtime"] == mtime:
        return _CACHE["atlas"]
    try:
        atlas = _Atlas(path.read_bytes())
    except (OSError, ValueError, KeyError, struct.error):
        _CACHE.update({"atlas": None, "mtime": mtime, "loaded": True})
        return None
    _CACHE.update({"atlas": atlas, "mtime": mtime, "loaded": True})
    _IMAGE_CACHE.clear()
    return atlas


def header() -> Dict[str, Any]:
    """The atlas header (empty dict when unavailable) — for diagnostics/tests."""
    atlas = _atlas()
    return dict(atlas.header) if atlas else {}


def frame_position(t: Any) -> float:
    """Fractional frame position for clock *t* (e.g. 18.4 = 40% from 18 to 19).

    The orb repaints at ~31 fps while the atlas is authored at 30 fps, so the
    fractional part matters: snapping to the nearest integer frame makes some
    source frames display twice and others once, which reads as a stutter. The
    painter uses this to blend between adjacent frames and keep the motion the
    smoothness the original has.
    """
    atlas = _atlas()
    if atlas is None:
        return 0.0
    try:
        clock = float(t)
    except (TypeError, ValueError):
        return 0.0
    if not math.isfinite(clock):
        return 0.0
    total = clock * atlas.frames / atlas.duration
    return total % atlas.frames


def frame_index(t: Any) -> int:
    """Frame index for clock time *t*, looping over the atlas duration.

    The modulo is computed on the FRAME COUNT rather than on seconds: doing
    ``(t % duration) * fps`` puts the loop seam one frame off, because
    ``1.2 + 2.4`` does not round-trip through float and lands just under the
    boundary (measured: frame 36 at t=1.2 vs 35 at t=3.6). Scaling by
    ``fps / duration`` and taking the integer modulo keeps the seam exact.
    """
    atlas = _atlas()
    if atlas is None:
        return 0
    position = frame_position(t)
    nearest = round(position)
    if abs(position - nearest) < 1e-9:
        position = float(nearest)
    return int(position) % atlas.frames


def frame_at_index(index: int) -> Optional[Tuple[Any, Tuple[float, float]]]:
    """(QImage, origin) for an explicit frame index, wrapping at the loop end."""
    atlas = _atlas()
    if atlas is None:
        return None
    index %= atlas.frames
    image = _IMAGE_CACHE.get(index)
    if image is None:
        try:
            from PySide6.QtGui import QImage
        except Exception:  # noqa: BLE001 - Tk fallback / headless without Qt
            return None
        data = atlas.rgba(index)
        if not data:
            return None
        image = QImage(data, atlas.w, atlas.h, atlas.w * 4,
                       QImage.Format.Format_RGBA8888).copy()
        if image.isNull():
            return None
        _IMAGE_CACHE[index] = image
    origin = (
        float(atlas.header.get("originX", atlas.w / 2)),
        float(atlas.header.get("originY", atlas.h)),
    )
    return image, origin


def frame_at(t: Any) -> Optional[Tuple[Any, Tuple[float, float]]]:
    """(QImage, (origin_x, origin_y)) for clock *t*, or None without Qt/atlas.

    Frames are cached by index: the atlas is small (72 frames) and the orb repaints
    continuously, so converting RGBA -> QImage per frame would dominate the paint.
    """
    atlas = _atlas()
    if atlas is None:
        return None
    index = frame_index(t)
    image = _IMAGE_CACHE.get(index)
    if image is None:
        try:
            from PySide6.QtGui import QImage
        except Exception:  # noqa: BLE001 - Tk fallback / headless without Qt
            return None
        data = atlas.rgba(index)
        if not data:
            return None
        image = QImage(data, atlas.w, atlas.h, atlas.w * 4,
                       QImage.Format.Format_RGBA8888).copy()
        if image.isNull():
            return None
        _IMAGE_CACHE[index] = image
    origin = (
        float(atlas.header.get("originX", atlas.w / 2)),
        float(atlas.header.get("originY", atlas.h)),
    )
    return image, origin
