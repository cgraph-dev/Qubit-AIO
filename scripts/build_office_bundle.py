"""Build the Qubit Office plugin bundle by inlining its modules.

WHY THIS EXISTS
---------------
The dashboard plugin loader injects exactly ONE `<script>` per manifest entry
(`frontend/qubit-web/src/plugins/usePlugins.ts`: `script.src = assetRoot/entry`).
It has no multi-script support, and extending it would mean editing shared code
that every other dashboard tab depends on.

So the Office's five source files are concatenated into one served bundle:

    iso-engine.js   the projection, the inverse, the depth key, the primitives
    sprites.js      baked, feet-anchored, outlined agent figures
    camera.js       fit / clamp / minimap transform / picking
    control-bar.js  the four read-only buttons and the six named refusals
    motion.js       paths, facing, stations
    qubit-office.js the renderer itself, which reads the globals the above set

The modules stay separate, readable, individually tested files. This script only
stitches them, so `qubit-office.js` on disk is never a 100 KB merge conflict.

WHAT IT GUARANTEES
------------------
* **Order is the dependency order.** Each module must be defined before the file
  that uses it; `ORDER` below is that order and the script asserts the globals
  each module is supposed to export actually appear.
* **Idempotent.** Running it twice produces byte-identical output, so a rebuild
  with no source change is a no-op (`--check` exits non-zero if the bundle is
  stale).
* **No timer, no write verb, no stray fetch** is introduced by stitching: the
  checks in `tests/test_office_tower_plugin.py` run against the *generated*
  bundle, so a module that smuggled one in fails the contract.

USAGE
-----
    .venv/bin/python scripts/build_office_bundle.py            # write the bundle
    .venv/bin/python scripts/build_office_bundle.py --check    # fail if stale
"""
from __future__ import annotations

import argparse
import hashlib
import os
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PLUGIN_DIR = REPO / "frontend" / "qubit-app" / "plugins" / "qubit-office"

#: (filename, the global it must define). Order is load order.
ORDER = [
    ("iso-engine.js", "window.QubitIso"),
    # The atlas loader must define its global BEFORE sprites.js reads it:
    # `sprites.js` does `var ATLAS = (root && root.QubitAtlas) || null` at load
    # time, so atlas.js has to be concatenated first. A2 owns both files.
    ("atlas.js", "window.QubitAtlas"),
    ("sprites.js", "window.QubitSprites"),
    ("camera.js", "window.QubitCamera"),
    ("control-bar.js", "window.QubitControlBar"),
    ("motion.js", "window.QubitOfficeMotion"),
]

#: The renderer reads the globals above, so it goes last.
RENDERER = "qubit-office.js"

BANNER = """/* ===========================================================================
 * QUBIT OFFICE — GENERATED BUNDLE. DO NOT EDIT THIS FILE DIRECTLY.
 *
 * Built by `scripts/build_office_bundle.py` from:
{parts}
 *
 * Edit those sources, then re-run the builder. Editing here means your change
 * is lost on the next build, and `--check` in CI will fail on it.
 * ===========================================================================
 */
"""


#: The guard is prepended/appended around the concatenated modules. It fails
#: LOUDLY at load time if a module did not define the global the next file needs
#: -- better a named error in the console than a canvas that silently draws
#: nothing, which is the exact failure mode this whole renderer has been fighting.
BANNER_GUARD_OPEN = """/* --- module load guard: a missing global must fail by name, not silently --- */
(function () {
  var root = (typeof window !== "undefined") ? window : globalThis;
  root.__qubit_require = function (dotted, file) {
    /* "window.QubitIso" -> "QubitIso": the LAST segment, not a fixed index.
     * Index 2 happens to work for "a.b.c" and returns undefined for "a.b",
     * which made the guard throw on a module that had loaded perfectly. */
    var parts = dotted.split(".");
    var name = parts[parts.length - 1];
    var got = root[name];
    if (got === undefined || got === null) {
      throw new Error(
        "qubit-office bundle: " + file + " did not define " + dotted +
        " (checked " + name + "). The module's export may be inside a " +
        "CommonJS `else` branch; it must assign the browser global " +
        "unconditionally.");
    }
    if (root.__qubit_loaded__) root.__qubit_loaded__.push(name);
    return got;
  };
  root.__qubit_loaded__ = [];
})();
"""

BANNER_GUARD_CLOSE = """/* --- end of bundle: modules proven present above --- */
"""


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def global_defined(src: str, dotted: str) -> bool:
    """Does this module actually assign the global it promises?

    `dotted` is like "window.QubitIso". We look for an assignment to that name
    on either `window` or the bare `root`/`self` alias the UMD headers use, or
    for a `module.exports` fallback. A module that forgets its export would
    otherwise bundle silently and the renderer would find `undefined`.
    """
    name = dotted.split(".")[-1]
    needles = (f"{dotted} =", f"root.{name} =", f"self.{name} =",
               f"window.{name} =", f"globalThis.{name} =")
    if not any(n in src for n in needles):
        return False
    # A bare `module.exports = ...` is NOT enough: two of these modules assign
    # their browser global only in the `else` of a CommonJS check, so they load
    # differently depending on how they are reached. Require the global to be
    # set on a root object somewhere in the source, unconditionally.
    return any(f"{alias}.{name} =" in src for alias in ("root", "window", "self",
                                                        "globalThis"))


def build() -> tuple[str, list[str]]:
    parts: list[tuple[str, str]] = []
    problems: list[str] = []

    for name, dotted in ORDER:
        path = PLUGIN_DIR / name
        if not path.is_file():
            problems.append(f"missing module: {name}")
            continue
        src = read(path)
        if not global_defined(src, dotted):
            problems.append(
                f"{name} does not appear to assign {dotted}; the bundle would "
                f"load it and the renderer would find `undefined`")
        parts.append((name, src))

    renderer = PLUGIN_DIR / RENDERER
    if not renderer.is_file():
        problems.append(f"missing renderer: {RENDERER}")
    else:
        parts.append((RENDERER, read(renderer)))

    if problems:
        return "", problems

    width = max(len(n) for n, _ in parts) + 2
    manifest = "\n".join(
        f" *   {n.ljust(width)} {len(s.splitlines())} lines" for n, s in parts)
    out = [BANNER.format(parts=manifest)]
    out.append(BANNER_GUARD_OPEN)
    for name, src in parts:
        out.append(f"\n/* ---- {name} " + "-" * (66 - len(name)) + " */\n")
        out.append(src if src.endswith("\n") else src + "\n")
        # After each module, prove the global it promised is actually there.
        # A silently-undefined global would render a dead canvas, which is
        # precisely the class of failure this bundle exists to stop.
        if name in dict(ORDER):
            dotted = dict(ORDER)[name]
            out.append(
                f"__qubit_require({json.dumps(dotted)}, "
                f"{json.dumps(name)});\n")
    out.append(BANNER_GUARD_CLOSE)
    return "".join(out), []


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if the bundle on disk is stale")
    ap.add_argument("--out", default=None,
                    help="output path (default: the bundle the plugin serves)")
    args = ap.parse_args()

    target = Path(args.out) if args.out else PLUGIN_DIR / "qubit-office.bundle.js"
    text, problems = build()
    if problems:
        print("BUNDLE REFUSED:", file=sys.stderr)
        for p in problems:
            print("  -", p, file=sys.stderr)
        return 2

    digest = hashlib.sha256(text.encode()).hexdigest()[:12]
    if args.check:
        if not target.is_file():
            print(f"STALE: {target.name} does not exist", file=sys.stderr)
            return 1
        current = target.read_text(encoding="utf-8")
        if current != text:
            print(f"STALE: {target.name} differs from its sources "
                  f"(would be {digest})", file=sys.stderr)
            return 1
        print(f"OK: {target.name} is up to date ({digest}, "
              f"{len(text.splitlines())} lines)")
        return 0

    # ATOMIC WRITE. `write_text` is a truncate-then-write: between the truncate
    # and the write completing, a reader sees an EMPTY or PARTIAL file. The
    # dashboard serves this exact path over HTTP, so a browser fetching during a
    # rebuild would receive a truncated bundle -- a syntax error, a dead canvas,
    # and a bug that looks like a code fault. `tests/test_office_atomic_serving.py`
    # measured it: a reader CAN observe a partial read without this.
    #
    # Write to a temp file in the SAME directory (so it is the same filesystem and
    # the rename is atomic) and then os.replace it over the target. A reader sees
    # either the whole old bundle or the whole new one, never a mixture.
    tmp = target.with_name(target.name + ".tmp")
    try:
        with open(tmp, "w", encoding="utf-8") as fh:
            fh.write(text)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, target)
    except BaseException:
        try:
            tmp.unlink()
        except OSError:
            pass
        raise
    print(f"wrote {target}")
    print(f"  {len(text.splitlines())} lines, {len(text)} bytes, sha256:{digest}")
    for name, _ in ORDER + [(RENDERER, "")]:
        p = PLUGIN_DIR / name
        if p.is_file():
            print(f"  + {name:<20} {len(p.read_text().splitlines()):>5} lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
