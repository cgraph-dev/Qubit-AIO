#!/usr/bin/env python3
"""Generate the provider/voice audit required by the provider plan P0.

Deterministic, no network, no LLM. Scans ``voicebridge/`` (excluding the
vendored ``qubit_runtime/`` fork) and records, for each provider/voice surface:

* canonical gateway/resolver callers;
* direct provider/ollama entry points (the bypass ratchet's symbol set);
* direct external HTTP call sites;
* the resolved streaming/capability defaults and the frontier transport flag.

Writes ``docs/archive/2026-09-21/QUBIT_PROVIDER_VOICE_AUDIT_2026-09-15.json`` and ``.md``.
"""
from __future__ import annotations

import argparse
import ast
import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PKG = REPO / "voicebridge"

RATCHET_SYMBOLS = {"chat_local", "chat_local_stream", "classify_with_ollama",
                   "summarize_ollama"}
SANCTIONED = {
    "voicebridge/local_llm.py",
    "voicebridge/providers/gateway.py",
    "voicebridge/providers/resolver.py",
    "voicebridge/agent.py",
    "voicebridge/chat_transport.py",
    "voicebridge/benchmarking/harness.py",
}
# Non-LLM external transports with their own gates (documented, not bypasses).
GATED_EXTERNAL = {
    "voicebridge/tts/openai_tts.py": "egress/estop guard before network",
    "voicebridge/tts/edge.py": "egress/estop guard before network",
    "voicebridge/media_gen.py": "estop + confirmation + credential + host allowlist",
    "voicebridge/messaging.py": "estop + fresh confirm + credential ref",
    "voicebridge/gateway_peers.py": "estop + confirm + https allowlist",
    "voicebridge/providers/frontier.py": "canonical frontier transport (gateway only)",
}

_EXTERNAL_HINT = re.compile(r"https?://(?!127\.0\.0\.1|localhost)")


def _iter_py():
    for p in sorted(PKG.rglob("*.py")):
        if "__pycache__" in p.as_posix():
            continue
        yield p


def _calls(tree) -> set:
    out = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            fn = node.func
            name = (fn.attr if isinstance(fn, ast.Attribute)
                    else fn.id if isinstance(fn, ast.Name) else "")
            if name:
                out.add(name)
    return out


def scan() -> dict:
    gateway_callers, resolver_callers, ratchet, external = [], [], [], []
    for path in _iter_py():
        rel = path.relative_to(REPO).as_posix()
        text = path.read_text(encoding="utf-8", errors="replace")
        try:
            names = _calls(ast.parse(text))
        except SyntaxError:
            names = set()
        if "run_role" in names:
            gateway_callers.append({"file": rel, "via": "gateway.run_role"})
        if "run" in names and "providers" in text and "gateway" in text:
            gateway_callers.append({"file": rel, "via": "gateway.run"})
        if "resolve" in names and "providers.resolver" in text:
            resolver_callers.append(rel)
        hit = sorted(names & RATCHET_SYMBOLS)
        if hit:
            ratchet.append({"file": rel, "symbols": hit,
                            "sanctioned": rel in SANCTIONED})
        if rel not in ("voicebridge/providers/frontier.py",) and \
                _EXTERNAL_HINT.search(text) and ("urllib" in text or "requests" in text):
            external.append({"file": rel,
                             "gate": GATED_EXTERNAL.get(rel, "unclassified")})

    return {
        "schema": "qubit-provider-voice-audit/1",
        "generated_from": "voicebridge/ (excludes qubit_runtime/ vendored fork)",
        "gateway_callers": sorted(gateway_callers, key=lambda r: r["file"]),
        "resolver_callers": sorted(set(resolver_callers)),
        "direct_provider_callers": ratchet,
        "external_http_calls": sorted(external, key=lambda r: r["file"]),
        "streaming": {
            "local": "real (local_llm.chat_local_stream, stream=true NDJSON)",
            "frontier": "request/response (frontier.py sets stream=false; no SSE)",
            "capability_defaults": {
                "local_profile": True,
                "external_profile": False,
                "allowlist_catalog_entry": False,
            },
        },
        "bypasses_unclassified": [r for r in ratchet
                                  if not r["sanctioned"]],
    }


def _md(d: dict) -> str:
    lines = ["# Qubit provider/voice audit — 2026-09-15", "",
             "Status: **machine-generated by `scripts/provider_voice_audit.py` "
             "(deterministic, no network, no LLM)**.", "",
             "Scope: `voicebridge/` only; the vendored `qubit_runtime/` fork and "
             "non-LLM transports with their own documented gates are excluded "
             "from the bypass set (`docs/archive/2026-09-21/QUBIT_PROVIDER_VOICE_PARITY_PLAN_2026-09-15.md` P0).",
             "", "## Canonical gateway callers", ""]
    for r in d["gateway_callers"]:
        lines.append(f"- `{r['file']}` — {r['via']}")
    lines += ["", "## Resolver callers", ""]
    lines += [f"- `{f}`" for f in d["resolver_callers"]]
    lines += ["", "## Direct provider/ollama entry points (ratchet)", "",
              "| file | symbols | sanctioned |", "| --- | --- | --- |"]
    for r in d["direct_provider_callers"]:
        lines.append(f"| `{r['file']}` | {', '.join(r['symbols'])} | "
                     f"{'yes' if r['sanctioned'] else 'NO — bypass'} |")
    lines += ["", "## External HTTP call sites (gate)", "",
              "| file | gate |", "| --- | --- |"]
    for r in d["external_http_calls"]:
        lines.append(f"| `{r['file']}` | {r['gate']} |")
    lines += ["", "## Streaming honesty", "",
              f"- local: {d['streaming']['local']}",
              f"- frontier: {d['streaming']['frontier']}",
              f"- capability defaults: `{json.dumps(d['streaming']['capability_defaults'])}`",
              "", "## Unclassified bypasses", ""]
    lines += ([f"- `{r['file']}`: {', '.join(r['symbols'])}"
               for r in d["bypasses_unclassified"]] or ["- none"])
    lines.append("")
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/archive/2026-09-21/QUBIT_PROVIDER_VOICE_AUDIT_2026-09-15")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    d = scan()
    base = REPO / args.out
    jtext = json.dumps(d, indent=1, sort_keys=True) + "\n"
    mtext = _md(d)
    jpath, mpath = Path(str(base) + ".json"), Path(str(base) + ".md")
    if args.check:
        ok = (jpath.is_file() and jpath.read_text() == jtext
              and mpath.is_file() and mpath.read_text() == mtext)
        print("OK: audit up to date" if ok else "STALE: regenerate")
        return 0 if ok else 1
    jpath.write_text(jtext, encoding="utf-8")
    mpath.write_text(mtext, encoding="utf-8")
    print(f"wrote {jpath.relative_to(REPO)} and {mpath.relative_to(REPO)}")
    print(f"gateway_callers={len(d['gateway_callers'])} "
          f"resolver_callers={len(d['resolver_callers'])} "
          f"direct={len(d['direct_provider_callers'])} "
          f"unclassified={len(d['bypasses_unclassified'])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
