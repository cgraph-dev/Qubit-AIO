#!/usr/bin/env python3
"""Packet 8T-F — generate shell completions from the real Qubit parsers.

Regenerate: python scripts/gen_completions.py  (writes voicebridge/_data/
completions/*). `qubit completion <shell>` prints them; the parity
test fails if committed completions drift from the parser.
Canonical launcher is `qubit`; `voicebridge` files are the byte-identical
compatibility alias (same command list, compat prog name in the header).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))


def _subcommands(parser: argparse.ArgumentParser) -> list:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return sorted(action.choices.keys())
    return []


def _bash(prog: str, cmds: list) -> str:
    words = " ".join(cmds)
    return f"""# Qubit Agent shell completion ({prog}, bash). Generated by
# scripts/gen_completions.py — do not hand-edit; regenerate instead.
_{prog.replace("-", "_")}_complete() {{
    local cur="{{COMP_WORDS[COMP_CWORD]}}"
    local cmds="{words}"
    if [ "$COMP_CWORD" -eq 1 ]; then
        COMPREPLY=($(compgen -W "$cmds" -- "$cur"))
    fi
}}
complete -F _{prog.replace("-", "_")}_complete {prog}
"""


def _zsh(prog: str, cmds: list) -> str:
    words = " ".join(cmds)
    return f"""# Qubit Agent shell completion ({prog}, zsh). Generated by
# scripts/gen_completions.py — do not hand-edit; regenerate instead.
#compdef {prog}
_{prog.replace("-", "_")}() {{
    local -a commands=({' '.join(cmds)})
    _describe '{prog} commands' commands
}}
compdef _{prog.replace("-", "_")} {prog}
"""


def _fish(prog: str, cmds: list) -> str:
    lines = [f"# Qubit Agent shell completion ({prog}, fish). Generated by",
             "# scripts/gen_completions.py — do not hand-edit; regenerate instead."]
    for cmd in cmds:
        lines.append(f"complete -c {prog} -n '__fish_use_subcommand' -f -a {cmd}")
    return "\n".join(lines) + "\n"


def main() -> int:
    import argparse as _ap

    ap = _ap.ArgumentParser()
    ap.add_argument("--outdir", default=None)
    ns = ap.parse_args()
    from voicebridge.cli import build_parser as build_voicebridge
    from voicebridge.terminal import build_parser as build_qubit_dev

    outdir = Path(ns.outdir) if ns.outdir else REPO / "voicebridge" / "_data" / "completions"
    outdir.mkdir(parents=True, exist_ok=True)
    vb = _subcommands(build_voicebridge())
    qd = ["help", "status", "health", "watch", "activity", "logs",
          "interrupt", "talk", "clear"]
    (outdir / "qubit.bash").write_text(_bash("qubit", vb))
    (outdir / "qubit.zsh").write_text(_zsh("qubit", vb))
    (outdir / "qubit.fish").write_text(_fish("qubit", vb))
    (outdir / "voicebridge.bash").write_text(_bash("voicebridge", vb))
    (outdir / "voicebridge.zsh").write_text(_zsh("voicebridge", vb))
    (outdir / "voicebridge.fish").write_text(_fish("voicebridge", vb))
    (outdir / "qubit-dev.bash").write_text(_bash("qubit-dev", qd))
    (outdir / "qubit-dev.zsh").write_text(_zsh("qubit-dev", qd))
    (outdir / "qubit-dev.fish").write_text(_fish("qubit-dev", qd))
    print(f"wrote 9 completions ({len(vb)} qubit commands)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
